def adjust_brightness(hex_color, steps):
    value = hex_color.lstrip("#")
    if len(value) == 3:
        value = "".join(ch * 2 for ch in value)
    parts = [value[i : i + 2] for i in range(0, 6, 2)]
    shifted = [max(0, min(255, int(part, 16) + steps)) for part in parts]
    return "#" + "".join(f"{part:02x}" for part in shifted)


